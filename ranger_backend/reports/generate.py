"""
generate_report(mission) -> Report. Synchronous (F16 fork 2).

Built from Postgres, not the live stream: the same mission produces the same
numbers every time. Only COMPLETED missions — a report over a mission still
taking data could not be reproduced.

All-or-nothing: the PDF is written to a temp file beside its destination,
fsynced, renamed into place, and the Report row is created after. If the row
fails, the file is removed. A row never points at a missing file, and a
failed run leaves no file behind.
"""
import base64
import hashlib
import io
import logging
import os
import secrets
import tempfile
from pathlib import Path

from django.conf import settings
from django.db import transaction
from django.template.loader import render_to_string
from django.utils import timezone

from core.exports import write_sensor_log_csv
from core.models import SensorLog
from missions.models import Mission

from . import branding as report_branding
from . import map as report_map
from . import stats
from . import thresholds
from .models import Report

# Bump when the PDF's content or layout changes meaningfully. Printed in the
# PDF and stored on the row, so any report can be traced to its generator.
REPORT_FORMAT_VERSION = "16.7b"

REPORTS_SUBDIR = "reports"


# ─── RANGER V3 START: 16-report-marking ───
# Page marking by the WEAKEST tier present (F16 fork 7). Every page carries
# it, because a report page gets separated from its cover: printed, cropped
# into a slide, attached on its own. LIVE and REPORTED carry no band.
MARKING = {
    SensorLog.Source.MODELLED.value: {
        "band": "MODELLED DATA — generated to match published statistics; "
                "individual values are not measurements",
        "watermark": None,
    },
    SensorLog.Source.SIMULATED.value: {
        "band": "SIMULATED DATA — generated by software; not measurements",
        "watermark": "SIMULATED",
    },
}


def page_marking(weakest: str | None) -> dict:
    return MARKING.get(weakest, {"band": None, "watermark": None})
# ─── RANGER V3 END: 16-report-marking ───


class ReportError(Exception):
    """The mission cannot be reported on as it stands. Message is user-facing."""


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _mission_rows(mission):
    """The mission's rows, scoped to the mission's org through the robot.

    Defence in depth (ADR-0006): a row on this mission from another org's
    robot is a data-integrity fault, and a report must not quietly include
    or quietly drop it. Refuse instead.
    """
    qs = SensorLog.objects.filter(mission=mission)
    foreign = qs.exclude(robot__organization_id=mission.organization_id).count()
    if foreign:
        raise ReportError(
            f"Mission {mission.pk} has {foreign} sensor log(s) from robots "
            f"outside its organization. Refusing to report on it."
        )
    return qs


def _csv_text(qs) -> str:
    full = (
        qs.select_related("robot", "mission")
        .prefetch_related("radiation_data", "air_quality_data", "imu_baro_data")
        .order_by("timestamp", "id")
    )
    buf = io.StringIO()
    write_sensor_log_csv(buf, full)
    return buf.getvalue()


def _write_atomic(dest: Path, data: bytes, suffix: str = ".pdf") -> None:
    """Write `data` to `dest` atomically and NEVER over an existing file.

    os.link fails if `dest` exists, where os.replace would silently clobber
    it. A report already on disk may already be in someone's hands; two rows
    pointing at one file is exactly the failure this refuses.
    """
    dest.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=dest.parent, prefix=".tmp-", suffix=suffix)
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(data)
            f.flush()
            os.fsync(f.fileno())
        os.link(tmp, dest)
    finally:
        Path(tmp).unlink(missing_ok=True)


def render_pdf(html: str, csv_text: str, csv_name: str) -> bytes:
    # Imported here so `manage.py check` and unrelated tests never load the
    # pango/cairo stack.
    from weasyprint import HTML, Attachment

    # fontTools logs one INFO line per font table it subsets (~230 per
    # report). setLevel(WARNING) alone does not stop it: WeasyPrint's
    # capture_logs('fontTools') sets that logger to DEBUG for the duration of
    # subsetting, and the records then propagate to the root console handler.
    # Cutting propagation keeps them at WeasyPrint's capture handler (which is
    # on the fontTools logger itself and re-logs real warnings through
    # WeasyPrint's own logger) and away from root.
    fonttools = logging.getLogger("fontTools")
    fonttools.setLevel(logging.WARNING)
    fonttools.propagate = False

    return HTML(string=html).write_pdf(
        attachments=[Attachment(string=csv_text, name=csv_name)]
    )


def _map_points(qs) -> list[dict]:
    rows = qs.order_by("timestamp", "id").values(
        "location", "timestamp", "source",
        "radiation_data__dose_rate_usvh", "radiation_data__radiation_value",
        "radiation_data__source",
        "air_quality_data__pm25", "air_quality_data__pm10",
        "air_quality_data__source",
    )
    return [{
        "lon": r["location"].x, "lat": r["location"].y,
        "timestamp": r["timestamp"], "source": r["source"],
        "dose_rate_usvh": r["radiation_data__dose_rate_usvh"],
        "cpm": r["radiation_data__radiation_value"],
        "radiation_source": r["radiation_data__source"],
        "pm25": r["air_quality_data__pm25"],
        "pm10": r["air_quality_data__pm10"],
        "air_quality_source": r["air_quality_data__source"],
    } for r in rows]


def _figures(mission, qs, points) -> dict:
    waypoints = [{"lon": w.location.x, "lat": w.location.y}
                 for w in mission.waypoints.order_by("order")]
    aoi = mission.area_of_interest
    detail = report_map.detail_figure(points, aoi=aoi, waypoints=waypoints)

    # The outline on the satellite scene: the AOI if the mission has one,
    # otherwise the extent of what was actually surveyed.
    if aoi is not None:
        survey = report_map.Extent(*aoi.extent)
    else:
        survey = report_map.bbox_of([p["lon"] for p in points],
                                    [p["lat"] for p in points])
    context = report_map.context_figure(mission, survey)
    return {"context": context, "detail": detail,
            "has_aoi": aoi is not None, "n_waypoints": len(waypoints)}


def _data_uri(png: bytes | None) -> str:
    return "data:image/png;base64," + base64.b64encode(png).decode() if png else ""


def generate_report(mission: Mission, *, user=None) -> Report:
    if mission.status != Mission.Status.COMPLETED:
        raise ReportError(
            f"Mission {mission.pk} is {mission.status}. Reports are generated "
            f"from COMPLETED missions only."
        )

    qs = _mission_rows(mission)
    rows = list(qs.order_by("timestamp", "id").values(*stats.ROW_COLUMNS))
    if not rows:
        raise ReportError(f"Mission {mission.pk} has no sensor logs.")

    summary = stats.summarise(rows)
    points = _map_points(qs)
    figures = _figures(mission, qs, points)
    summary["comparisons"] = thresholds.compare(summary, points)
    brand = report_branding.branding(mission.organization)
    summary["branding"] = {"accent": brand["accent"], "logo": brand["logo"] is not None}
    # What the map shows is part of the audit record, not just pixels.
    summary["map"] = {
        "context": figures["context"].meta or {"omitted": figures["context"].omitted},
        "detail": figures["detail"].meta or {"omitted": figures["detail"].omitted},
    }
    csv_text = _csv_text(qs)
    csv_sha = _sha256(csv_text.encode("utf-8"))

    generated_at = timezone.now()
    stamp = generated_at.strftime("%Y%m%dT%H%M%SZ")
    csv_name = f"mission-{mission.pk}-{stamp}-data.csv"

    html = render_to_string("reports/report.html", {
        "mission": mission,
        "organization": mission.organization,
        "robot": mission.robot,
        "generated_at": generated_at,
        "generated_by": user,
        "format_version": REPORT_FORMAT_VERSION,
        "summary": summary,
        "tiers": stats.TIERS,
        # Templates can't index a dict by a variable: flatten for the table.
        "matrix_rows": [
            (kind, [counts[t] for t in stats.TIERS])
            for kind, counts in summary["provenance_matrix"].items()
        ],
        "csv_name": csv_name,
        "csv_sha256": csv_sha,
        "context": figures["context"],
        "context_src": _data_uri(figures["context"].png),
        "detail": figures["detail"],
        "detail_src": _data_uri(figures["detail"].png),
        "colour_bar_src": _data_uri(report_map.colour_bar_png()),
        "has_aoi": figures["has_aoi"],
        "marking": page_marking(summary["weakest_source"]),
        "brand": brand,
        "n_waypoints": figures["n_waypoints"],
    })
    pdf = render_pdf(html, csv_text, csv_name)
    pdf_sha = _sha256(pdf)

    # The random token keeps names unique even when two generations in the
    # same second produce byte-identical PDFs (WeasyPrint is deterministic
    # within a second: CreationDate is its only varying field).
    rel = Path(REPORTS_SUBDIR) / mission.organization.slug / (
        f"mission-{mission.pk}-{stamp}-{pdf_sha[:8]}-{secrets.token_hex(4)}.pdf"
    )
    dest = Path(settings.MEDIA_ROOT) / rel
    # ─── RANGER V3 START: 16-report-download ───
    # The CSV is the exact bytes embedded in the PDF (same csv_sha256), stored
    # beside it under the same unique stem.
    csv_rel = rel.with_suffix(".csv")
    csv_dest = Path(settings.MEDIA_ROOT) / csv_rel
    _write_atomic(dest, pdf)
    try:
        _write_atomic(csv_dest, csv_text.encode("utf-8"), suffix=".csv")
    except BaseException:
        dest.unlink(missing_ok=True)
        raise
    # ─── RANGER V3 END: 16-report-download ───

    try:
        with transaction.atomic():
            return Report.objects.create(
                organization=mission.organization,
                mission=mission,
                generated_by=user,
                generated_at=generated_at,
                format_version=REPORT_FORMAT_VERSION,
                pdf_path=str(rel),
                pdf_sha256=pdf_sha,
                csv_path=str(csv_rel),
                csv_sha256=csv_sha,
                row_count=summary["row_count"],
                weakest_source=summary["weakest_source"],
                summary=summary,
            )
    except BaseException:
        dest.unlink(missing_ok=True)
        csv_dest.unlink(missing_ok=True)
        raise
# ─── RANGER V3 END: 16-report-generate ───
